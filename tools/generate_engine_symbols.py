#!/usr/bin/env python3
"""Generate the deterministic ProtoDroid engine-symbol index from re/functions.csv."""

import argparse
import csv
from pathlib import Path

IMAGE_BASE = 0x10000000


def c_literal(value: bytes) -> str:
    out = []
    for byte in value:
        if byte == 0:
            out.append("\\000")
        elif byte == 34:
            out.append('\\"')
        elif byte == 92:
            out.append("\\\\")
        elif 32 <= byte < 127:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03o}")
    return "".join(out)


def generate(source: Path) -> str:
    names = bytearray()
    offsets = {}
    records = []
    with source.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            entry = int(row["entry"], 16)
            if not IMAGE_BASE < entry < IMAGE_BASE + 0x10000000:
                continue
            name = row["name"].strip()
            namespace = row["namespace"].strip()
            if not name or any(ord(c) < 32 or ord(c) > 126 for c in name + namespace):
                continue
            qualified = name if not namespace or namespace == "Global" else namespace + "::" + name
            encoded = qualified.encode("ascii")
            if len(encoded) > 4095:
                continue
            offset = offsets.get(qualified)
            if offset is None:
                offset = len(names)
                offsets[qualified] = offset
                names.extend(encoded + b"\0")
            records.append((qualified, offset, entry - IMAGE_BASE))
    records.sort(key=lambda item: (item[0], item[2]))
    lines = [
        "// Generated by tools/generate_engine_symbols.py from re/functions.csv; do not edit.",
        f"// {len(records)} function records; duplicate names use ascending-RVA 1-based ordinals.",
        "static const char kModSymbolNames[] =",
    ]
    # Adjacent literals keep individual compiler tokens small while retaining one compact string table.
    position = 0
    while position < len(names):
        chunk = bytes(names[position:position + 768])
        # Do not split a UTF-8 sequence (input is ASCII) or worry about escape boundaries: c_literal is per chunk.
        lines.append(f'    "{c_literal(chunk)}"')
        position += len(chunk)
    if not names:
        lines.append('    ""')
    lines[-1] += ";"
    lines.append("static const ModSymbolRecord kModSymbolRecords[] = {")
    lines.extend(f"    {{{offset}u, 0x{rva:08x}u}}," for _, offset, rva in records)
    lines.append("};")
    lines.append(f"constexpr size_t kModSymbolCount = {len(records)};")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path("re/functions.csv"))
    parser.add_argument("--output", type=Path, default=Path("src/native/mod_symbols.inc"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.source)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != result:
            raise SystemExit("mod_symbols.inc is stale; run tools/generate_engine_symbols.py")
        print("Engine symbol index is reproducible")
    else:
        args.output.write_text(result, encoding="utf-8")
        print(f"Generated {args.output} ({len(result)} bytes)")


if __name__ == "__main__":
    main()
